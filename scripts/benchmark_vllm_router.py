#!/usr/bin/env python
"""Benchmark an already-running vLLM Router through its ``/generate`` API.

Input requests use the deployment service contract::

    {"data": {"query": "查天气", "top_k": 2}}

Each output line on stdout is the same JSON array returned by ``calc``.  Timing
diagnostics and the aggregate summary are written to stderr so stdout remains
machine-readable.
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass
import json
from pathlib import Path
import re
import statistics
import sys
from time import perf_counter
from typing import Any, Mapping, Sequence
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen


_DEFAULT_QUERY = "查天气"
_DEFAULT_SYSTEM_PROMPT = (
    "Select every Agent Skill needed for the user request in execution order. "
    "Output one hierarchical skill code per line, with no other text."
)


class BenchmarkError(RuntimeError):
    """Raised when the benchmark request or Router bundle is invalid."""


@dataclass(frozen=True, slots=True)
class RouterBundle:
    system_prompt: str
    num_levels: int
    virtual_tokens: tuple[str, ...]
    path_skill_names: Mapping[tuple[str, ...], tuple[str, ...]]


@dataclass(frozen=True, slots=True)
class BenchmarkRequest:
    original: Mapping[str, Any]
    query: str
    top_k: int


@dataclass(frozen=True, slots=True)
class BenchmarkResult:
    index: int
    output: tuple[str, ...]
    latency_ms: float
    completion_tokens: int
    raw_completion: str


def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--model-dir",
        required=True,
        help="Router model bundle containing tokenizer and decode artifacts.",
    )
    parser.add_argument(
        "--url",
        default="http://127.0.0.1:18000/generate",
        help="vLLM generation endpoint (default: %(default)s).",
    )
    parser.add_argument(
        "--input",
        help="Optional JSONL file containing project-format requests.",
    )
    parser.add_argument(
        "--query",
        action="append",
        help="Query to benchmark; repeat this option for multiple queries.",
    )
    parser.add_argument("--top-k", type=int, default=2)
    parser.add_argument(
        "--max-code-paths",
        type=int,
        default=2,
        help="Maximum paths generated by the deployed Router (default: 2).",
    )
    parser.add_argument("--repeat", type=int, default=1)
    parser.add_argument("--warmup", type=int, default=1)
    parser.add_argument("--concurrency", type=int, default=1)
    parser.add_argument("--timeout", type=float, default=300.0)
    parser.add_argument(
        "--trust-remote-code",
        action=argparse.BooleanOptionalAction,
        default=False,
    )
    parser.add_argument(
        "--show-raw",
        action="store_true",
        help="Print raw completion text with per-request timing on stderr.",
    )
    return parser.parse_args(argv)


def _read_json_object(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise BenchmarkError(f"required file does not exist: {path}")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise BenchmarkError(f"invalid JSON file: {path}") from exc
    if not isinstance(payload, dict):
        raise BenchmarkError(f"JSON root must be an object: {path}")
    return payload


def _load_bundle(model_dir: Path) -> RouterBundle:
    decode_map = _read_json_object(model_dir / "skill_decode_map.json")
    manifest = _read_json_object(model_dir / "router_manifest.json")
    token_path = model_dir / "virtual_tokens.txt"
    if not token_path.is_file():
        raise BenchmarkError(f"required file does not exist: {token_path}")
    virtual_tokens = tuple(
        line.strip()
        for line in token_path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    )
    if not virtual_tokens:
        raise BenchmarkError("virtual_tokens.txt is empty")
    if decode_map.get("virtual_tokens") != list(virtual_tokens):
        raise BenchmarkError(
            "virtual_tokens.txt disagrees with skill_decode_map.json"
        )
    num_levels = decode_map.get("num_levels")
    if not isinstance(num_levels, int) or isinstance(num_levels, bool) or num_levels < 1:
        raise BenchmarkError("skill_decode_map.json has invalid num_levels")
    skills = decode_map.get("skills")
    paths = decode_map.get("paths")
    if not isinstance(skills, Mapping) or not isinstance(paths, list):
        raise BenchmarkError("skill_decode_map.json has invalid skills or paths")

    path_skill_names: dict[tuple[str, ...], tuple[str, ...]] = {}
    for raw_path in paths:
        if not isinstance(raw_path, Mapping):
            raise BenchmarkError("skill_decode_map.json contains an invalid path")
        tokens = raw_path.get("tokens")
        skill_ids = raw_path.get("skill_ids")
        if (
            not isinstance(tokens, list)
            or len(tokens) != num_levels
            or any(not isinstance(token, str) for token in tokens)
            or not isinstance(skill_ids, list)
        ):
            raise BenchmarkError("skill_decode_map.json contains an invalid path")
        names: list[str] = []
        for skill_id in skill_ids:
            metadata = skills.get(skill_id) if isinstance(skill_id, str) else None
            if not isinstance(metadata, Mapping):
                raise BenchmarkError(f"unknown Skill ID in path: {skill_id!r}")
            names.append(str(metadata.get("name") or skill_id))
        path_skill_names[tuple(tokens)] = tuple(names)

    system_prompt = manifest.get("system_prompt", _DEFAULT_SYSTEM_PROMPT)
    if not isinstance(system_prompt, str):
        raise BenchmarkError("router_manifest.json has invalid system_prompt")
    return RouterBundle(
        system_prompt=system_prompt,
        num_levels=num_levels,
        virtual_tokens=virtual_tokens,
        path_skill_names=path_skill_names,
    )


def _load_tokenizer(model_dir: Path, *, trust_remote_code: bool) -> Any:
    try:
        from transformers import AutoTokenizer
    except ImportError as exc:
        raise BenchmarkError("benchmark requires transformers") from exc
    return AutoTokenizer.from_pretrained(
        str(model_dir),
        trust_remote_code=trust_remote_code,
        local_files_only=True,
    )


def _render_prompt(tokenizer: Any, query: str, system_prompt: str) -> str:
    messages: list[dict[str, str]] = []
    if system_prompt:
        messages.append({"role": "system", "content": system_prompt})
    messages.append({"role": "user", "content": query.strip()})
    apply_template = getattr(tokenizer, "apply_chat_template", None)
    if getattr(tokenizer, "chat_template", None) and callable(apply_template):
        try:
            return str(
                apply_template(
                    messages,
                    tokenize=False,
                    add_generation_prompt=True,
                    enable_thinking=False,
                )
            )
        except TypeError:
            return str(
                apply_template(
                    messages,
                    tokenize=False,
                    add_generation_prompt=True,
                )
            )
    system = f"System: {system_prompt.strip()}\n" if system_prompt else ""
    return f"{system}User: {query.strip()}\nAssistant:"


def _load_requests(args: argparse.Namespace) -> list[BenchmarkRequest]:
    raw_requests: list[Mapping[str, Any]] = []
    if args.input:
        input_path = Path(args.input).expanduser().resolve()
        for line_number, line in enumerate(
            input_path.read_text(encoding="utf-8").splitlines(), start=1
        ):
            if not line.strip():
                continue
            try:
                payload = json.loads(line)
            except json.JSONDecodeError as exc:
                raise BenchmarkError(
                    f"invalid JSON at {input_path}:{line_number}"
                ) from exc
            if not isinstance(payload, Mapping):
                raise BenchmarkError(
                    f"request at {input_path}:{line_number} is not an object"
                )
            raw_requests.append(payload)
    for query in args.query or ():
        raw_requests.append({"data": {"query": query, "top_k": args.top_k}})
    if not raw_requests:
        raw_requests.append(
            {"data": {"query": _DEFAULT_QUERY, "top_k": args.top_k}}
        )

    requests: list[BenchmarkRequest] = []
    for payload in raw_requests:
        data = payload.get("data", {})
        request = data if isinstance(data, Mapping) else {}
        query = str(request.get("query", _DEFAULT_QUERY)).strip()
        raw_top_k = request.get("top_k", request.get("topk", args.top_k))
        try:
            top_k = int(raw_top_k)
        except (TypeError, ValueError) as exc:
            raise BenchmarkError(f"invalid top_k value: {raw_top_k!r}") from exc
        top_k = min(max(1, top_k), args.max_code_paths)
        requests.append(
            BenchmarkRequest(original=payload, query=query, top_k=top_k)
        )
    return requests


def _post_json(url: str, payload: Mapping[str, Any], timeout: float) -> Any:
    body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    request = Request(
        url,
        data=body,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urlopen(request, timeout=timeout) as response:
            raw = response.read().decode("utf-8")
    except HTTPError as exc:
        details = exc.read().decode("utf-8", errors="replace")
        raise BenchmarkError(
            f"vLLM returned HTTP {exc.code}: {details[:1000]}"
        ) from exc
    except URLError as exc:
        raise BenchmarkError(f"cannot reach vLLM endpoint {url}: {exc}") from exc
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise BenchmarkError(f"vLLM returned invalid JSON: {raw[:1000]}") from exc


def _extract_completion_text(payload: Any, prompt: str) -> str:
    text: Any = None
    if isinstance(payload, Mapping):
        text = payload.get("text")
        if text is None:
            text = payload.get("generated_text")
        if text is None and isinstance(payload.get("outputs"), list):
            outputs = payload["outputs"]
            if outputs and isinstance(outputs[0], Mapping):
                text = outputs[0].get("text")
    if isinstance(text, list):
        text = text[0] if text else None
    if not isinstance(text, str):
        raise BenchmarkError(
            "vLLM response has no supported text field; response="
            + json.dumps(payload, ensure_ascii=False, default=str)[:1000]
        )
    return text[len(prompt) :] if text.startswith(prompt) else text


def _decode_skill_names(
    completion: str,
    bundle: RouterBundle,
    *,
    top_k: int,
) -> list[str]:
    token_pattern = re.compile(
        "|".join(
            re.escape(token)
            for token in sorted(bundle.virtual_tokens, key=len, reverse=True)
        )
    )
    generated_tokens = token_pattern.findall(completion)
    names: list[str] = []
    seen: set[str] = set()
    for offset in range(0, len(generated_tokens), bundle.num_levels):
        path = tuple(generated_tokens[offset : offset + bundle.num_levels])
        if len(path) != bundle.num_levels:
            break
        members = bundle.path_skill_names.get(path)
        if members is None:
            continue
        for name in members:
            if name not in seen:
                names.append(name)
                seen.add(name)
                if len(names) >= top_k:
                    return names
    return names


def _run_one(
    *,
    index: int,
    request: BenchmarkRequest,
    tokenizer: Any,
    bundle: RouterBundle,
    url: str,
    timeout: float,
) -> BenchmarkResult:
    if not request.query:
        return BenchmarkResult(index, (), 0.0, 0, "")
    prompt = _render_prompt(tokenizer, request.query, bundle.system_prompt)
    separator_ids = tokenizer.encode("\n", add_special_tokens=False)
    max_tokens = (
        request.top_k * bundle.num_levels
        + max(0, request.top_k - 1) * max(1, len(separator_ids))
        + 1
    )
    payload = {
        "prompt": prompt,
        "stream": False,
        "temperature": 0.0,
        "max_tokens": max_tokens,
        "min_tokens": bundle.num_levels,
        "skip_special_tokens": False,
        "spaces_between_special_tokens": False,
    }
    started = perf_counter()
    response = _post_json(url, payload, timeout)
    latency_ms = (perf_counter() - started) * 1000.0
    completion = _extract_completion_text(response, prompt)
    completion_tokens = len(
        tokenizer.encode(completion, add_special_tokens=False)
    )
    names = _decode_skill_names(completion, bundle, top_k=request.top_k)
    return BenchmarkResult(
        index=index,
        output=tuple(names),
        latency_ms=latency_ms,
        completion_tokens=completion_tokens,
        raw_completion=completion,
    )


def _percentile(values: Sequence[float], percentile: float) -> float:
    ordered = sorted(values)
    if not ordered:
        return 0.0
    position = (len(ordered) - 1) * percentile
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    fraction = position - lower
    return ordered[lower] * (1.0 - fraction) + ordered[upper] * fraction


def _print_summary(results: Sequence[BenchmarkResult], wall_seconds: float) -> None:
    latencies = [result.latency_ms for result in results]
    total_tokens = sum(result.completion_tokens for result in results)
    summary = {
        "requests": len(results),
        "wall_seconds": round(wall_seconds, 6),
        "qps": round(len(results) / wall_seconds, 4) if wall_seconds > 0 else 0.0,
        "completion_tokens_per_second": (
            round(total_tokens / wall_seconds, 4) if wall_seconds > 0 else 0.0
        ),
        "latency_ms": {
            "min": round(min(latencies), 3),
            "mean": round(statistics.fmean(latencies), 3),
            "p50": round(_percentile(latencies, 0.50), 3),
            "p95": round(_percentile(latencies, 0.95), 3),
            "p99": round(_percentile(latencies, 0.99), 3),
            "max": round(max(latencies), 3),
        },
    }
    print(
        "[benchmark-vllm-router] "
        + json.dumps(summary, ensure_ascii=False),
        file=sys.stderr,
    )


def main(argv: Sequence[str] | None = None) -> int:
    try:
        args = _parse_args(argv)
        if args.repeat < 1 or args.warmup < 0 or args.concurrency < 1:
            raise BenchmarkError("repeat/concurrency must be positive; warmup non-negative")
        if args.max_code_paths < 1 or args.timeout <= 0:
            raise BenchmarkError("max-code-paths and timeout must be positive")

        model_dir = Path(args.model_dir).expanduser().resolve()
        if not model_dir.is_dir():
            raise BenchmarkError(f"model directory does not exist: {model_dir}")
        bundle = _load_bundle(model_dir)
        tokenizer = _load_tokenizer(
            model_dir, trust_remote_code=bool(args.trust_remote_code)
        )
        base_requests = _load_requests(args)

        for warmup_index in range(args.warmup):
            _run_one(
                index=warmup_index,
                request=base_requests[warmup_index % len(base_requests)],
                tokenizer=tokenizer,
                bundle=bundle,
                url=args.url,
                timeout=args.timeout,
            )
        if args.warmup:
            print(
                f"[benchmark-vllm-router] warmup complete: {args.warmup}",
                file=sys.stderr,
            )

        jobs = [request for _ in range(args.repeat) for request in base_requests]
        started = perf_counter()
        completed: list[BenchmarkResult] = []
        with ThreadPoolExecutor(max_workers=args.concurrency) as executor:
            futures = {
                executor.submit(
                    _run_one,
                    index=index,
                    request=request,
                    tokenizer=tokenizer,
                    bundle=bundle,
                    url=args.url,
                    timeout=args.timeout,
                ): index
                for index, request in enumerate(jobs)
            }
            for future in as_completed(futures):
                completed.append(future.result())
        wall_seconds = perf_counter() - started
        completed.sort(key=lambda item: item.index)

        for result in completed:
            print(json.dumps(list(result.output), ensure_ascii=False))
            details = {
                "index": result.index,
                "latency_ms": round(result.latency_ms, 3),
                "completion_tokens": result.completion_tokens,
                "results": len(result.output),
            }
            if args.show_raw:
                details["raw_completion"] = result.raw_completion
            print(
                "[benchmark-vllm-router] "
                + json.dumps(details, ensure_ascii=False),
                file=sys.stderr,
            )
        _print_summary(completed, wall_seconds)
    except (BenchmarkError, OSError, ValueError) as exc:
        print(f"[benchmark-vllm-router] ERROR: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
